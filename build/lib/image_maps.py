"""Image Map integration: image files -> Bedrock map data + item frames."""
from __future__ import annotations

import os
import subprocess

from . import consts as C


ASSET_DIR = os.path.join(os.path.dirname(__file__), "..", "assets", "characters")
IMAGE_EXTS = (".png", ".jpg", ".jpeg", ".webp")

# 2x2 maps per side wall. IDs are fixed so validation and placement are stable.
MAP_W = 2
MAP_H = 2
LEFT_START_ID = 1000
RIGHT_START_ID = 1100
KITCHEN_START_ID = 2000
OUTDOOR_START_ID = 3000

IMAGE_PLANS = [
    ("ちいかわとはちわれ", LEFT_START_ID),
    ("ちいかわとはちわれ_2", RIGHT_START_ID),
    ("シーサーと鎧さん", KITCHEN_START_ID),
    ("ちいかわラーメン", OUTDOOR_START_ID),
]


def _project_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def _imagemap_cmd() -> str:
    exe = os.path.join(_project_root(), "tools", "ImageMap4-Windows", "ImageMap-cmd.exe")
    if not os.path.isfile(exe):
        raise FileNotFoundError(f"ImageMap-cmd.exe not found: {exe}")
    return exe


def _list_images() -> list[str]:
    if not os.path.isdir(ASSET_DIR):
        return []
    files = [
        os.path.join(ASSET_DIR, name)
        for name in os.listdir(ASSET_DIR)
        if os.path.splitext(name)[1].lower() in IMAGE_EXTS
    ]
    files.sort()
    return files


def _find_image(stem: str) -> str:
    for path in _list_images():
        if os.path.splitext(os.path.basename(path))[0] == stem:
            return path
    raise FileNotFoundError(f"Image not found in build/assets/characters: {stem}")


def _import_image(world_path: str, image_path: str, start_id: int):
    subprocess.run(
        [
            _imagemap_cmd(),
            world_path,
            "--import", image_path,
            "--size", f"{MAP_W},{MAP_H}",
            "--scaling", "bicubic",
            "--fill", "uniform",
            "--algorithm", "good",
            "--dithering", "none",
            "--id", str(start_id),
        ],
        check=True,
    )


def _ids(start_id: int) -> list[list[int]]:
    # ImageMap uses x-left->right, y-top->bottom. IDs are row-major for 2x2.
    return [
        [start_id, start_id + 1],
        [start_id + 2, start_id + 3],
    ]


def _place_map_panel(w, *, side: str, start_id: int):
    ids = _ids(start_id)
    base_y = C.FEET_Y + 3  # top row y=-56, bottom y=-57: visible above seats.
    center_z = 6
    if side == "west":
        x = C.SHOP_X_MIN
        facing = 5  # east, into the room
        z0 = center_z - 1
        for row in range(MAP_H):
            for col in range(MAP_W):
                w.set_filled_map_frame(x, base_y - row, z0 + col, ids[row][col], facing)
    elif side == "east":
        x = C.SHOP_X_MAX
        facing = 4  # west, into the room
        z0 = center_z - 1
        for row in range(MAP_H):
            for col in range(MAP_W):
                w.set_filled_map_frame(x, base_y - row, z0 + col, ids[row][col], facing)
    elif side == "kitchen":
        z = C.SHOP_Z_BACK
        facing = 3  # south, into the room
        x0 = -1
        for row in range(MAP_H):
            for col in range(MAP_W):
                w.set_filled_map_frame(x0 + col, base_y - row, z, ids[row][col], facing)
    elif side == "outdoor":
        z = C.SHOP_Z_FRONT - 4
        backing_z = z + 1
        facing = 2  # south/front, toward the plaza spawn
        x0 = -7
        for row in range(MAP_H):
            for col in range(MAP_W):
                # South-facing frames are viewed from the plaza; reverse block x so the image reads left-to-right.
                x = x0 + (MAP_W - 1 - col)
                y = base_y - row
                w.set_block(x, y, backing_z, "yellow_concrete")
                w.set_filled_map_frame(x, y, z, ids[row][col], facing)
        for x in (x0, x0 + 1):
            w.set_block(x, C.FEET_Y, backing_z, "oak_fence")
    else:
        raise ValueError(side)


def place_image_map_frames(w):
    """Place item frames that will display maps generated by import_image_maps."""
    _place_map_panel(w, side="west", start_id=LEFT_START_ID)
    _place_map_panel(w, side="east", start_id=RIGHT_START_ID)
    _place_map_panel(w, side="kitchen", start_id=KITCHEN_START_ID)
    _place_map_panel(w, side="outdoor", start_id=OUTDOOR_START_ID)


def import_image_maps(world_path: str):
    """Generate Bedrock map data for the planned character images."""
    try:
        _imagemap_cmd()
    except FileNotFoundError as exc:
        print(f"  [image-map] skip: {exc}")
        print("  [image-map] place ImageMap-cmd.exe under tools/ImageMap4-Windows/ to generate map data.")
        return
    for stem, start_id in IMAGE_PLANS:
        path = _find_image(stem)
        _import_image(world_path, path, start_id)
        print(f"  [image-map] {stem}: {os.path.basename(path)} -> map {start_id}-{start_id + 3}")